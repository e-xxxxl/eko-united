import type { Metadata } from "next";
import Image from "next/image";
import { notFound } from "next/navigation";
import { apiFetch } from "@/lib/api";
import type { DemoPlayer } from "@/lib/demoData";
import { isAllowedImageUrl } from "@/lib/imageHosts";
import { playerPhotoUrl } from "@/lib/squad";
import { pageMeta } from "@/lib/seo";
import LightboxTrigger, { type LightboxPhoto } from "@/components/Lightbox";

async function getPlayer(slug: string): Promise<DemoPlayer | null> {
  return await apiFetch<DemoPlayer>(`/players/${slug}`, 1800);
}

export async function generateMetadata({
  params,
}: {
  params: Promise<{ slug: string }>;
}): Promise<Metadata> {
  const { slug } = await params;
  const player = await getPlayer(slug);
  if (!player) return { title: "Player Not Found" };

  const number = typeof player.squadNumber === "number" ? `, number ${player.squadNumber}` : "";
  const role = player.role === "player" ? player.position : player.title || player.position;
  const description = role
    ? `${player.name}: ${role} for Eko United FC${number}. Profile, stats and photos.`
    : `${player.name} at Eko United FC. Profile and photos.`;

  // The share image is generated by opengraph-image.tsx in this folder.
  return pageMeta({ title: player.name, description, path: `/team/${player.slug}` });
}

export default async function PlayerProfilePage({
  params,
}: {
  params: Promise<{ slug: string }>;
}) {
  const { slug } = await params;
  const player = await getPlayer(slug);
  if (!player) notFound();

  const jsonLd = {
    "@context": "https://schema.org",
    "@type": "Person",
    name: player.name,
    nationality: player.nationality,
    memberOf: { "@type": "SportsTeam", name: "Eko United FC" },
    ...(player.role === "player" && player.position ? { jobTitle: player.position } : {}),
  };

  const mainPhoto = playerPhotoUrl(player.photoUrl, player.photoCutout);
  const extraPhotos = (player.extraPhotos || [])
    .filter(isAllowedImageUrl)
    .slice(0, 2)
    .map((u) => playerPhotoUrl(u, player.photoCutout) as string);

  const viewerPhotos: LightboxPhoto[] = [
    ...(mainPhoto ? [{ src: mainPhoto, alt: player.name }] : []),
    ...extraPhotos.map((src, i) => ({ src, alt: `${player.name}, photo ${i + 2}` })),
  ];

  const stats = [
    { label: "Appearances", value: player.stats?.appearances ?? 0 },
    { label: "Goals", value: player.stats?.goals ?? 0 },
    { label: "Assists", value: player.stats?.assists ?? 0 },
  ];

  return (
    <main>
      <script
        type="application/ld+json"
        dangerouslySetInnerHTML={{ __html: JSON.stringify(jsonLd) }}
      />

      <section className="grid grid-cols-[minmax(0,1fr)] gap-10 px-6 py-16 sm:px-10 lg:grid-cols-[380px_minmax(0,1fr)] lg:px-16">
        <div className="min-w-0">
          <div className="relative mx-auto aspect-[3/4] w-full max-w-md overflow-hidden rounded-2xl lg:max-w-none">
            {mainPhoto ? (
              <LightboxTrigger photos={viewerPhotos} index={0} label={`Enlarge photo of ${player.name}`} className="absolute inset-0 h-full">
                <Image
                  src={mainPhoto}
                  alt={player.name}
                  fill
                  priority
                  sizes="(min-width: 1024px) 380px, 90vw"
                  className="object-cover object-top"
                />
              </LightboxTrigger>
            ) : (
              <div className="absolute inset-0 rounded-2xl bg-navy/[0.06]" />
            )}
          </div>
          {extraPhotos.length > 0 && (
            <div className="mx-auto mt-3 grid max-w-md grid-cols-2 gap-3 lg:max-w-none">
              {extraPhotos.map((src, i) => (
                <div key={src} className="relative aspect-[3/4] overflow-hidden rounded-xl">
                  <LightboxTrigger
                    photos={viewerPhotos}
                    index={(mainPhoto ? 1 : 0) + i}
                    label={`Enlarge photo ${i + 2} of ${player.name}`}
                    className="absolute inset-0 h-full"
                  >
                    <Image
                      src={src}
                      alt={`${player.name}, photo ${i + 2}`}
                      fill
                      sizes="(min-width: 1024px) 190px, 45vw"
                      className="object-cover object-top"
                    />
                  </LightboxTrigger>
                </div>
              ))}
            </div>
          )}
        </div>

        <div>
          <p className="mb-3 flex items-baseline gap-3 text-xs font-semibold uppercase tracking-[0.3em] text-cyan">
            {typeof player.squadNumber === "number" && (
              <span className="font-display text-5xl leading-none tracking-normal">{player.squadNumber}</span>
            )}
            {player.position || "Eko United FC"}
          </p>
          <h1 className="display-title font-display font-bold">{player.name}</h1>

          <dl className="mt-8 grid grid-cols-2 gap-6 sm:grid-cols-3">
            {player.nationality && (
              <div>
                <dt className="text-xs uppercase tracking-wide text-navy/40">Nationality</dt>
                <dd className="mt-1 text-base font-semibold text-navy">{player.nationality}</dd>
              </div>
            )}
            {player.dateOfBirth && (
              <div>
                <dt className="text-xs uppercase tracking-wide text-navy/40">Date of Birth</dt>
                <dd className="mt-1 text-base font-semibold text-navy">
                  {new Date(player.dateOfBirth).toLocaleDateString("en-GB", {
                    day: "numeric",
                    month: "long",
                    year: "numeric",
                    timeZone: "Africa/Lagos",
                  })}
                </dd>
              </div>
            )}
          </dl>

          {player.role === "player" && (
            <div className="mt-10 flex gap-10 bg-navy-dark px-6 py-6">
              {stats.map((stat) => (
                <div key={stat.label}>
                  <p className="font-display text-3xl text-yellow">{stat.value}</p>
                  <p className="mt-1 text-xs uppercase tracking-wide text-white/50">
                    {stat.label}
                  </p>
                </div>
              ))}
            </div>
          )}

          {player.bio && (
            <p className="mt-8 max-w-2xl text-base leading-relaxed text-navy/70">
              {player.bio}
            </p>
          )}
        </div>
      </section>
    </main>
  );
}
